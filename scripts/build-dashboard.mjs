// Generates dashboard/data.js (embedded JSON so the dashboard works offline and on static hosting)
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { join } from "node:path";
import { DATA_DIR, ROOT, nowIso } from "./lib.mjs";

export async function buildDashboard() {
  let listings = [];
  try {
    listings = JSON.parse(await readFile(join(DATA_DIR, "listings.json"), "utf8"));
  } catch {}

  const payload = {
    generatedAt: nowIso(),
    listings,
  };
  await mkdir(join(ROOT, "dashboard"), { recursive: true });
  await writeFile(
    join(ROOT, "dashboard", "data.js"),
    "// generated by scripts/build-dashboard.js — do not edit\nwindow.NNEXT = " + JSON.stringify(payload, null, 1) + ";\n"
  );
  console.log(`dashboard/data.js written (${listings.length} listings)`);
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  buildDashboard().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
