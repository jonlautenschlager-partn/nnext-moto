// Generates dashboard/data.js (embedded JSON so the dashboard works offline and on static hosting)
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { join } from "node:path";
import { DATA_DIR, ROOT, nowIso } from "./lib.mjs";

export async function buildDashboard() {
  let listings = [];
  try {
    listings = JSON.parse(await readFile(join(DATA_DIR, "listings.json"), "utf8"));
  } catch {}

  const payload = {
    generatedAt: nowIso(),
    listings,
  };
  await mkdir(join(ROOT, "app"), { recursive: true });
  await writeFile(
    join(ROOT, "app", "data.js"),
    "// generated by scripts/build-dashboard.mjs — do not edit\nwindow.NNEXT = " + JSON.stringify(payload, null, 1) + ";\n"
  );
  console.log(`app/data.js written (${listings.length} listings)`);

  // public copy of the model KB (specs only — no personal data) so the
  // dashboard can recompute the A2 verdict right after an edit
  try {
    const kb = JSON.parse(await readFile(join(ROOT, "knowledge-base", "models.json"), "utf8"));
    const slim = {
      generatedAt: nowIso(),
      models: (kb.models || []).map((m) => ({
        make: m.make, name: m.name, stockKw: m.stockKw, kg: m.kg,
        restrictedAvailable: m.restrictedAvailable, type: m.type,
      })),
    };
    await writeFile(join(ROOT, "app", "kb.json"), JSON.stringify(slim, null, 1) + "\n");
    console.log(`app/kb.json written (${slim.models.length} models)`);
  } catch {
    console.log("app/kb.json skipped (no models.json)");
  }
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  buildDashboard().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
